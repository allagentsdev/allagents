import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { strict as assert } from 'node:assert';
const phase = process.argv[2] ?? 'before';
const root = await mkdtemp(`/tmp/allagents-588-${phase}-`);
const home = join(root, 'home');
const project = join(root, 'project');
const cli = join(process.cwd(), 'dist/index.js');
const legacy = join(home, '.config/Code/User/mcp.json');
const current = join(home, '.copilot/mcp-config.json');
await mkdir(join(home, '.allagents'), { recursive: true });
await mkdir(project, { recursive: true });
const workspace = join(home, '.allagents/workspace.yaml');
await writeFile(workspace, 'repositories: []\nplugins: []\nclients: [vscode]\nmcpServers:\n  managed:\n    command: managed-mcp\n');
async function run(args: string[]) {
  const proc = Bun.spawn(['bun', cli, '--json', ...args], { cwd: project, env: { ...process.env, HOME: home, ALLAGENTS_TEST_HOME: home, APPDATA: join(home, 'AppData/Roaming'), COPILOT_HOME: undefined }, stdout: 'pipe', stderr: 'pipe' });
  const [code, stdout, stderr] = await Promise.all([proc.exited, new Response(proc.stdout).text(), new Response(proc.stderr).text()]);
  console.log(JSON.stringify({ args, code, stdout: JSON.parse(stdout), stderr }));
  assert.equal(code, 0);
}
await run(['mcp', 'update', '--scope', 'user', '--offline']);
console.log(JSON.stringify({ root, legacyCreated: existsSync(legacy), copilotCreated: existsSync(current) }));
if (phase === 'before') { assert.equal(existsSync(legacy), true); } else { assert.equal(existsSync(legacy), false); assert.equal(existsSync(current), false); }
await mkdir(join(home, '.config/Code/User'), { recursive: true });
const legacyBytes = '{\n  // User configuration must survive\n  "servers": {"personal": {"command": "personal-mcp"}, "managed": {"command": "old-managed"}}\n}\n';
await writeFile(legacy, legacyBytes);
await writeFile(join(home, '.allagents/sync-state.json'), JSON.stringify({ version: 1, lastSync: '2026-01-01T00:00:00Z', files: {}, mcpServers: { vscode: ['managed'] } }));
await run(['mcp', 'update', '--scope', 'user', '--offline']);
console.log(JSON.stringify({ legacyUntouched: await readFile(legacy, 'utf8') === legacyBytes }));
if (phase !== 'before') assert.equal(await readFile(legacy, 'utf8'), legacyBytes);
await mkdir(join(home, '.copilot'), { recursive: true });
await writeFile(current, JSON.stringify({ mcpServers: { personal: { command: 'personal-mcp' }, conflict: { command: 'user-conflict' } } }));
await writeFile(workspace, 'repositories: []\nplugins: []\nclients: [vscode, copilot]\nmcpServers:\n  managed:\n    command: managed-mcp\n  conflict:\n    command: desired-conflict\n');
await run(['mcp', 'update', '--scope', 'user', '--offline']);
let config = JSON.parse(await readFile(current, 'utf8'));
assert.equal(config.mcpServers.personal.command, 'personal-mcp');
assert.equal(config.mcpServers.conflict.command, 'user-conflict');
assert.equal(config.mcpServers.managed.command, 'managed-mcp');
if (phase !== 'before') assert.equal(await readFile(legacy, 'utf8'), legacyBytes);
await run(['mcp', 'update', '--scope', 'user', '--offline']);
await writeFile(workspace, 'repositories: []\nplugins: []\nclients: [vscode, copilot]\nmcpServers: {}\n');
await run(['mcp', 'update', '--scope', 'user', '--offline']);
config = JSON.parse(await readFile(current, 'utf8'));
assert.deepEqual(config.mcpServers, { personal: { command: 'personal-mcp' }, conflict: { command: 'user-conflict' } });
await mkdir(join(project, '.allagents'));
await writeFile(join(project, '.allagents/workspace.yaml'), 'repositories: []\nplugins: []\nclients: [vscode, copilot]\nmcpServers:\n  local:\n    command: project-mcp\n');
await run(['mcp', 'update', '--offline']);
assert.equal(JSON.parse(await readFile(join(project, '.vscode/mcp.json'), 'utf8')).servers.local.command, 'project-mcp');
assert.equal(JSON.parse(await readFile(join(project, '.github/mcp.json'), 'utf8')).mcpServers.local.command, 'project-mcp');
console.log(JSON.stringify({ result: 'passed', phase, root, checks: ['user vscode destination', 'legacy preservation', 'copilot conflict preservation/add/idempotence/remove', 'separate project destinations'] }));
